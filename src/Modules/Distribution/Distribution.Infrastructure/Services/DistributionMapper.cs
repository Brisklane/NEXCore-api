    /// <summary>Percentage of a denominator that may legitimately be zero.</summary>
    public static decimal Percent(decimal numerator, decimal denominator)
        => denominator == 0 ? 0 : Math.Round(numerator / denominator * 100, 2);

    private static bool IsOpen(Domain.Enums.ClaimStatus status) => status
        is Domain.Enums.ClaimStatus.Submitted
        or Domain.Enums.ClaimStatus.UnderReview
        or Domain.Enums.ClaimStatus.QueryRaised
        or Domain.Enums.ClaimStatus.Resubmitted
        or Domain.Enums.ClaimStatus.Approved
        or Domain.Enums.ClaimStatus.PartiallyApproved;
