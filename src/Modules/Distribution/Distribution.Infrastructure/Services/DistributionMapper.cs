using Distribution.Application.DTOs;
using Distribution.Domain.Entities;

namespace Distribution.Infrastructure.Services;

/// <summary>
/// Entity → DTO projections shared across the services.
///
/// Hand-written rather than reflective on purpose: several of these carry derived fields
/// (days-to-expiry, effective credit limit, achievement pace) that only make sense against a
/// clock, and a convention-based mapper would silently drop them.
///
/// Roll-up fields that need a second query — outlet counts, month-to-date sales, credit — are
/// left at their defaults here and filled by the calling service, which knows whether the caller
/// is paying for them.
/// </summary>
public static class DistributionMapper
{
