using Nexcore.SharedKernel;

namespace Crm.Domain.Entities
{
    /// <summary>
    /// Products/line items associated with a Deal (Opportunity Product).
    /// Aligned with Salesforce OpportunityLineItem, Dynamics Opportunity Product, HubSpot Line Items.
    /// </summary>
    public class DealProduct : BaseEntity
    {
        // ??? Keys ??????????????????????????????????????????????????????
        public Guid DealId { get; set; }
        public Deal Deal { get; set; } = null!;

        public Guid ProductId { get; set; }
        public Product Product { get; set; } = null!;

        public Guid? PricebookEntryId { get; set; }
        public PricebookEntry? PricebookEntry { get; set; }

        // ??? Pricing ???????????????????????????????????????????????????
        public decimal Quantity { get; set; } = 1;
        public decimal UnitPrice { get; set; }          // Sales price (can differ from list)
        public decimal ListPrice { get; set; }          // Original list price from pricebook
        public decimal? Discount { get; set; }          // Percentage discount
        public decimal TotalPrice { get; set; }         // Quantity x UnitPrice after discount

        // ??? Sorting ???????????????????????????????????????????????????
        public int? SortOrder { get; set; }
    }
}
