using Nexcore.SharedKernel;

namespace Crm.Domain.Entities
{
    /// <summary>
    /// An email message sent or received, linked to CRM records.
    /// Aligned with Salesforce EmailMessage, HubSpot Email Engagement, Dynamics Email Activity.
    /// </summary>
    public class EmailMessage : BaseEntity
    {
        // ??? Basic Info ????????????????????????????????????????????????
        public string Subject { get; set; } = string.Empty;
        public string? HtmlBody { get; set; }
        public string? TextBody { get; set; }

        // ??? Addresses ?????????????????????????????????????????????????
        public string? FromAddress { get; set; }
        public string? FromName { get; set; }
        public string? ToAddress { get; set; }    // Comma-separated
        public string? CcAddress { get; set; }
        public string? BccAddress { get; set; }

        // ??? Direction ?????????????????????????????????????????????????
        public bool Incoming { get; set; }         // false = outbound
        public DateTime? MessageDate { get; set; }

        // ??? Status ????????????????????????????????????????????????????
        public bool IsRead { get; set; }
        public bool HasAttachment { get; set; }
        public bool IsTracked { get; set; }        // Open/click tracking

        // ??? Tracking ??????????????????????????????????????????????????
        public int OpenCount { get; set; }
        public DateTime? FirstOpenDate { get; set; }
        public int ClickCount { get; set; }
        public DateTime? FirstClickDate { get; set; }

        // ??? Related To ????????????????????????????????????????????????
        public Guid? RelatedToId { get; set; }
        public string? RelatedToType { get; set; }  // "Deal", "Case", "Account", "Lead", "Contact"

        // ??? Thread ????????????????????????????????????????????????????
        public string? MessageId { get; set; }         // RFC 2822 Message-Id header
        public string? InReplyToId { get; set; }       // Thread chaining
        public string? ThreadIdentifier { get; set; }  // Conversation grouping

        // ??? Sender ????????????????????????????????????????????????????
        public Guid? SentByUserId { get; set; }

        // ??? Navigation ????????????????????????????????????????????????
        public ICollection<Attachment> Attachments { get; set; } = new List<Attachment>();
    }
}
