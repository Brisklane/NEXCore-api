using Crm.Domain.Enums;
using Nexcore.SharedKernel;

namespace Crm.Domain.Entities
{
    /// <summary>
    /// A knowledge base article used to help resolve cases.
    /// Aligned with Salesforce Knowledge Article, Dynamics Knowledge Base Record, Zendesk Article.
    /// </summary>
    public class KnowledgeArticle : BaseEntity
    {
        // ??? Basic Info ????????????????????????????????????????????????
        public string ArticleNumber { get; set; } = string.Empty;  // Auto-generated
        public string Title { get; set; } = string.Empty;          // Required
        public string? UrlName { get; set; }                        // SEO-friendly slug

        // ??? Classification ????????????????????????????????????????????
        public string? ArticleType { get; set; }     // FAQ, How-To, Policy, Known Issue
        public string? CategoryGroup { get; set; }   // Product area / topic
        public ArticleStatus Status { get; set; } = ArticleStatus.Draft;

        // ??? Content ???????????????????????????????????????????????????
        public string? Summary { get; set; }
        public string Body { get; set; } = string.Empty;

        // ??? Visibility ????????????????????????????????????????????????
        public bool IsVisibleInApp { get; set; } = true;       // Agent portal
        public bool IsVisibleInCsp { get; set; }               // Customer self-service portal
        public bool IsVisibleInPkb { get; set; }               // Public knowledge base

        // ??? Lifecycle ?????????????????????????????????????????????????
        public DateTime? PublishedDate { get; set; }
        public DateTime? ArchivedDate { get; set; }
        public int VersionNumber { get; set; } = 1;

        // ??? Ownership ?????????????????????????????????????????????????
        public Guid? OwnerId { get; set; }

        // ??? Navigation ????????????????????????????????????????????????
        public ICollection<Attachment> Attachments { get; set; } = new List<Attachment>();
    }
}
