using Nexcore.SharedKernel;

namespace Crm.Domain.Entities
{
    /// <summary>
    /// A sales target/quota for a user, team, or territory over a period.
    /// Aligned with Salesforce Forecasting Quota, Dynamics Sales Goal, SAP Sales Target.
    /// </summary>
    public class SalesTarget : BaseEntity
    {
        // ??? Target Owner ??????????????????????????????????????????????
        public Guid? UserId { get; set; }        // Individual rep target
        public Guid? TeamId { get; set; }        // Team-level target
        public Guid? TerritoryId { get; set; }   // Territory target

        // ??? Period ????????????????????????????????????????????????????
        public int FiscalYear { get; set; }
        public int? FiscalQuarter { get; set; }  // 1-4, null = annual
        public int? FiscalMonth { get; set; }    // 1-12, null = not monthly

        public DateTime PeriodStartDate { get; set; }
        public DateTime PeriodEndDate { get; set; }

        // ??? Target Values ?????????????????????????????????????????????
        public decimal TargetAmount { get; set; }
        public int? TargetDealsCount { get; set; }     // Number of deals target

        // ??? Actuals (computed/updated externally) ?????????????????????
        public decimal? ActualAmount { get; set; }
        public int? ActualDealsCount { get; set; }

        // ??? Currency ??????????????????????????????????????????????????
        public string CurrencyCode { get; set; } = "USD";

    }
}
