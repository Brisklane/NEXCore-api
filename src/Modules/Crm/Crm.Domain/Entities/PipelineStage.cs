using Nexcore.SharedKernel;

namespace Crm.Domain.Entities
{
    /// <summary>
    /// An individual stage within a sales pipeline.
    /// Aligned with HubSpot Deal Stage, Salesforce Opportunity Stage, Dynamics Opportunity Sales Stage.
    /// </summary>
    public class PipelineStage : BaseEntity
    {
        // ??? Keys ??????????????????????????????????????????????????????
        public Guid PipelineId { get; set; }
        public Pipeline Pipeline { get; set; } = null!;

        // ??? Basic Info ????????????????????????????????????????????????
        public string StageName { get; set; } = string.Empty;  // Required
        public int DisplayOrder { get; set; }                   // Sort order in pipeline
        public decimal ProbabilityPercent { get; set; }         // Win probability (0-100)

        // ??? Category ??????????????????????????????????????????????????
        public bool IsWon { get; set; }   // Terminal stage: won
        public bool IsLost { get; set; }  // Terminal stage: lost

        // ??? Forecast ??????????????????????????????????????????????????
        public string? ForecastCategory { get; set; }  // Pipeline, BestCase, Commit, Omitted, Closed

        // ??? Navigation ????????????????????????????????????????????????
        public ICollection<Deal> Deals { get; set; } = new List<Deal>();
    }
}
