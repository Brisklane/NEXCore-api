using Crm.Domain.Enums;
using Nexcore.SharedKernel;

namespace Crm.Domain.Entities
{
    /// <summary>
    /// A formal pricing proposal sent to a customer.
    /// Aligned with Salesforce Quote, Dynamics Quote, HubSpot Quotes, SAP Quotation.
    /// </summary>
    public class Quote : BaseEntity
    {
        // ??? Basic Info ????????????????????????????????????????????????
        public string QuoteNumber { get; set; } = string.Empty;  // Auto-generated
        public string QuoteName { get; set; } = string.Empty;    // Required

        // ??? Links ?????????????????????????????????????????????????????
        public Guid DealId { get; set; }
        public Deal Deal { get; set; } = null!;

        public Guid? PricebookId { get; set; }
        public Pricebook? Pricebook { get; set; }

        public Guid? ContactId { get; set; }
        public Contact? Contact { get; set; }

        public Guid? AccountId { get; set; }
        public Account? Account { get; set; }

        // ??? Status ????????????????????????????????????????????????????
        public QuoteStatus Status { get; set; } = QuoteStatus.Draft;
        public bool IsSyncing { get; set; }   // Syncing amount back to Deal

        // ??? Dates ?????????????????????????????????????????????????????
        public DateTime? ExpirationDate { get; set; }

        // ??? Financial ?????????????????????????????????????????????????
        public decimal Subtotal { get; set; }
        public decimal? Discount { get; set; }          // Overall discount %
        public decimal? Tax { get; set; }
        public decimal? ShippingAndHandling { get; set; }
        public decimal GrandTotal { get; set; }

        // ??? Billing Address ???????????????????????????????????????????
        public string? BillingStreet { get; set; }
        public string? BillingCity { get; set; }
        public string? BillingState { get; set; }
        public string? BillingPostalCode { get; set; }
        public string? BillingCountry { get; set; }

        // ??? Shipping Address ??????????????????????????????????????????
        public string? ShippingStreet { get; set; }
        public string? ShippingCity { get; set; }
        public string? ShippingState { get; set; }
        public string? ShippingPostalCode { get; set; }
        public string? ShippingCountry { get; set; }

        // ??? Notes ?????????????????????????????????????????????????????
        public string? TermsAndConditions { get; set; }

        // ??? Ownership ?????????????????????????????????????????????????
        public Guid? OwnerId { get; set; }

        // ??? Navigation ????????????????????????????????????????????????
        public ICollection<QuoteLineItem> LineItems { get; set; } = new List<QuoteLineItem>();
    }
}
