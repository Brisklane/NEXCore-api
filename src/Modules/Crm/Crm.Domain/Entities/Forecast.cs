        public int? FiscalMonth { get; set; }   // 1-12, null = quarterly

        public DateTime PeriodStartDate { get; set; }
        public DateTime PeriodEndDate { get; set; }

        // ??? Forecast Amounts ??????????????????????????????????????????
        public decimal PipelineAmount { get; set; }   // All open deals
        public decimal BestCaseAmount { get; set; }
        public decimal CommitAmount { get; set; }
        public decimal ClosedAmount { get; set; }
        public decimal? AdjustedAmount { get; set; }  // Manager override

        // ??? Quota ?????????????????????????????????????????????????????
        public decimal? QuotaAmount { get; set; }

        // ??? Currency ??????????????????????????????????????????????????
