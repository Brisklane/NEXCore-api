using Nexcore.SharedKernel;

namespace Crm.Domain.Entities
{
    /// <summary>
    /// Represents a product or service that can be sold.
    /// Aligned with Salesforce Product2, Dynamics ProductCatalog, SAP Material.
    /// </summary>
    public class Product : BaseEntity
    {
        // ??? Basic Info ????????????????????????????????????????????????
        public string ProductName { get; set; } = string.Empty;  // Required
        public string? ProductCode { get; set; }
        public string? ProductFamily { get; set; }  // Software, Hardware, Services, etc.

        // ??? Pricing ???????????????????????????????????????????????????

        // ??? Unit ??????????????????????????????????????????????????????
        public string? QuantityUnit { get; set; }  // Each, Hour, Day, Month, License, GB
        public decimal? QuantityUnitPrice { get; set; }  // Standard/default price

        // ??? Navigation ????????????????????????????????????????????????
        public ICollection<PricebookEntry> PricebookEntries { get; set; } = new List<PricebookEntry>();
        public ICollection<QuoteLineItem> QuoteLineItems { get; set; } = new List<QuoteLineItem>();
        public ICollection<OrderLineItem> OrderLineItems { get; set; } = new List<OrderLineItem>();
        public ICollection<DealProduct> DealProducts { get; set; } = new List<DealProduct>();
    }
}
