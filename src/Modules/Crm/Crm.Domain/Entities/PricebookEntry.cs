using Nexcore.SharedKernel;

namespace Crm.Domain.Entities
{
    /// <summary>
    /// A junction between a Product and a Pricebook - stores the price of a product in a specific pricebook.
    /// Aligned with Salesforce PricebookEntry, Dynamics Price List Item.
    /// </summary>
    public class PricebookEntry : BaseEntity
    {
        // ??? Keys ??????????????????????????????????????????????????????
        public Guid PricebookId { get; set; }
        public Pricebook Pricebook { get; set; } = null!;

        public Guid ProductId { get; set; }
        public Product Product { get; set; } = null!;

        // ??? Pricing ???????????????????????????????????????????????????
        public decimal UnitPrice { get; set; }          // List price
        public bool UseStandardPrice { get; set; }      // If true, inherits from standard pricebook

        // ??? Currency ??????????????????????????????????????????????????
        public string CurrencyCode { get; set; } = "USD";
    }
}
