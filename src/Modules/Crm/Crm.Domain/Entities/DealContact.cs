using Nexcore.SharedKernel;

namespace Crm.Domain.Entities
{
    /// <summary>
    /// Many-to-many junction between Deals and Contacts (Contact Roles).
    /// Aligned with Salesforce OpportunityContactRole, Dynamics Connection, HubSpot Associations.
    /// </summary>
    public class DealContact : BaseEntity
    {
        // ??? Keys ??????????????????????????????????????????????????????
        public Guid DealId { get; set; }
        public Deal Deal { get; set; } = null!;

        public Guid ContactId { get; set; }
        public Contact Contact { get; set; } = null!;

        // ??? Role ??????????????????????????????????????????????????????
        public string? Role { get; set; }     // Decision Maker, Influencer, Technical Buyer, Economic Buyer, Champion, Other
        public bool IsPrimary { get; set; }   // Primary contact for the deal
    }
}
