using Nexcore.SharedKernel;
using Sales.Domain.Enums;

namespace Sales.Domain.Entities;

/// <summary>
/// A cashier session on a POS terminal.
/// Tracks opening/closing float, total sales, and cash reconciliation.
/// Scoped to a Branch via the inherited <c>BranchId</c> from <see cref="BaseEntity"/>.
/// </summary>
public class PosSession : BaseEntity
{
    public string SessionNumber { get; set; } = string.Empty;

    public Guid PosTerminalId { get; set; }
    public PosTerminal PosTerminal { get; set; } = null!;

    // ??? Cashier ??????????????????????????????????????????????????????????????
    /// <summary>
    /// The cashier who opened this session.
    /// FK to <see cref="PosCashier"/> which in turn holds the Hr.Employee FK.
    /// </summary>
    public Guid PosCashierId { get; set; }
    public PosCashier PosCashier { get; set; } = null!;

    public PosSessionStatus Status { get; set; } = PosSessionStatus.Open;

    public DateTime OpenedAt { get; set; } = DateTime.UtcNow;
    public DateTime? ClosedAt { get; set; }

    // ??? Float ????????????????????????????????????????????????????????????????
    public decimal OpeningFloat { get; set; }
    public string? OpeningNotes { get; set; }
    /// <summary>JSON-serialized List&lt;DenominationCountDto&gt; counted at open.</summary>
    public string? OpeningDenominationsJson { get; set; }

    public decimal ClosingFloat { get; set; }
    public decimal ExpectedClosingFloat { get; set; }
    public decimal FloatVariance { get; set; }
    /// <summary>JSON-serialized List&lt;DenominationCountDto&gt; counted at close.</summary>
    public string? ClosingDenominationsJson { get; set; }

    // ??? Totals ???????????????????????????????????????????????????????????????
    public decimal TotalSalesAmount { get; set; }
    public decimal TotalRefundsAmount { get; set; }
    public decimal TotalDiscountsAmount { get; set; }
    public decimal TotalTaxAmount { get; set; }
    public decimal NetSalesAmount { get; set; }

    // ??? Payment Breakdown ????????????????????????????????????????????????????
    public decimal CashCollected { get; set; }
    public decimal CardCollected { get; set; }
    public decimal WalletCollected { get; set; }
    public decimal OtherCollected { get; set; }

    public int TransactionCount { get; set; }
    public string? ClosingNotes { get; set; }

    // ??? Navigation ???????????????????????????????????????????????????????????
    public ICollection<PosTransaction> Transactions { get; set; } = new List<PosTransaction>();
    public ICollection<PosCashMovement> CashMovements { get; set; } = new List<PosCashMovement>();
    public ICollection<PosCashDrawerEvent> DrawerEvents { get; set; } = new List<PosCashDrawerEvent>();
}
