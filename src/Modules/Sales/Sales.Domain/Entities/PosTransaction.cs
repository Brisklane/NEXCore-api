using Nexcore.SharedKernel;
using Sales.Domain.Enums;

namespace Sales.Domain.Entities;

/// <summary>
/// A single POS transaction (sale, refund, void, exchange).
/// Core transactional record at the point of sale.
/// </summary>
public class PosTransaction : BaseEntity
{
    // ??? Identity ?????????????????????????????????????????????????????????????
    public string TransactionNumber { get; set; } = string.Empty;
    public string? ReceiptNumber { get; set; }

    // ??? Session & Terminal ???????????????????????????????????????????????????
    public Guid PosSessionId { get; set; }
    public PosSession PosSession { get; set; } = null!;

    public Guid PosTerminalId { get; set; }
    public PosTerminal PosTerminal { get; set; } = null!;

    public Guid PosStoreId { get; set; }
    public PosStore PosStore { get; set; } = null!;

    // ??? Cashier ??????????????????????????????????????????????????????????????
    /// <summary>
    /// Cashier who processed this transaction.
    /// FK to <see cref="PosCashier"/> which holds the Hr.Employee FK.
    /// </summary>
    public Guid PosCashierId { get; set; }
    public PosCashier PosCashier { get; set; } = null!;

    // ??? Customer ?????????????????????????????????????????????????????????????
    /// <summary>Cross-module reference to Crm.Contact. Null for walk-in / anonymous. ID only.</summary>
    public Guid? ContactId { get; set; }

    // ??? Type & Status ????????????????????????????????????????????????????????
    public PosTransactionType TransactionType { get; set; } = PosTransactionType.Sale;
    public PosTransactionStatus Status { get; set; } = PosTransactionStatus.InProgress;

    public DateTime TransactionDate { get; set; } = DateTime.UtcNow;

    // ??? Financials ???????????????????????????????????????????????????????????
    public decimal SubtotalAmount { get; set; }
    public decimal DiscountAmount { get; set; }
    public decimal TaxAmount { get; set; }
    public decimal RoundingAmount { get; set; }
    public decimal TotalAmount { get; set; }
    public decimal TenderedAmount { get; set; }
    public decimal ChangeAmount { get; set; }

    // ??? Coupon / Loyalty ?????????????????????????????????????????????????????
    public string? CouponCode { get; set; }
    public decimal CouponDiscountAmount { get; set; }
    public decimal LoyaltyPointsEarned { get; set; }
    public decimal LoyaltyPointsRedeemed { get; set; }

    // ??? Refund / Void Link ???????????????????????????????????????????????????
    /// <summary>For refunds and voids: the original transaction being reversed.</summary>
    public Guid? OriginalTransactionId { get; set; }
    public PosTransaction? OriginalTransaction { get; set; }

    // ??? Sales Order Link ?????????????????????????????????????????????????????
    /// <summary>
    /// Sales Order this transaction pays against.
    ///
    /// Scenarios:
    ///   • Standard walk-in sale  ? SalesOrder created in Draft, this transaction
    ///     pays it in full, status moves to PaidAndClosed.
    ///   • Lay-away / deposit     ? SalesOrder stays in PartiallyPaid until
    ///     a final PosTransaction clears the balance.
    ///   • Parked order payment   ? Customer returns, cashier resumes the
    ///     SalesOrder (PosParked) and this transaction completes it.
    ///   • Null                   ? Anonymous quick-sale with no saved order.
    /// </summary>
    public Guid? SalesOrderId { get; set; }
    public SalesOrder? SalesOrder { get; set; }

    public string? Notes { get; set; }

    // ??? Navigation ???????????????????????????????????????????????????????????
    public ICollection<PosTransactionLine> Lines { get; set; } = new List<PosTransactionLine>();
    public ICollection<PosPayment> Payments { get; set; } = new List<PosPayment>();
}
