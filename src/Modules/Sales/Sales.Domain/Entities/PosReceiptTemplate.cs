using Nexcore.SharedKernel;

namespace Sales.Domain.Entities;

/// <summary>
/// Receipt template configuration for a POS store.
/// Controls what appears on printed and digital receipts.
/// The inherited <c>BranchId</c> / <c>CompanyId</c> from <see cref="BaseEntity"/>
/// scope this template to the correct company branch.
/// </summary>
public class PosReceiptTemplate : BaseEntity
{
    public string TemplateName { get; set; } = string.Empty;

    // ??? Header ???????????????????????????????????????????????????????????????
    /// <summary>Overrides Branch.Name if set. Shows on top of the receipt.</summary>
    public string? HeaderBusinessName { get; set; }

    /// <summary>
    /// Overrides Branch.Address if set.
    /// Falls back to Core.Branch.Address when null.
    /// </summary>
    public string? HeaderAddressLine1 { get; set; }
    public string? HeaderAddressLine2 { get; set; }
    public string? HeaderPhone { get; set; }
    public string? HeaderEmail { get; set; }
    public string? HeaderWebsite { get; set; }
    public string? TaxRegistrationNumber { get; set; }

    public string? LogoUrl { get; set; }

    /// <summary>Free-text header message printed above the line items.</summary>
    public string? HeaderMessage { get; set; }

    // ??? Footer ???????????????????????????????????????????????????????????????
    /// <summary>Free-text footer message (e.g., "Thank you for shopping with us!").</summary>
    public string? FooterMessage { get; set; }

    /// <summary>Return/refund policy text printed at the bottom.</summary>
    public string? ReturnPolicy { get; set; }

    // ??? Display Options ??????????????????????????????????????????????????????
    public bool ShowBarcode { get; set; } = true;
    public bool ShowQrCode { get; set; }
    public bool ShowCashierName { get; set; } = true;
    public bool ShowCustomerName { get; set; } = true;
    public bool ShowDiscountLine { get; set; } = true;
    public bool ShowTaxBreakdown { get; set; } = true;
    public bool ShowLoyaltyPoints { get; set; } = true;
    public bool ShowSavingsAmount { get; set; } = true;

    // ??? Format ???????????????????????????????????????????????????????????????
    /// <summary>Thermal80mm, Thermal58mm, A4.</summary>
    public string PaperSize { get; set; } = "Thermal80mm";

    public bool IsDefault { get; set; }

    // ??? Print behaviour ??????????????????????????????????????????????????????
    /// <summary>Number of copies the POS device prints per receipt.</summary>
    public int PrintCopies { get; set; } = 1;

    /// <summary>Send the auto-cut command after printing (thermal printers).</summary>
    public bool AutoCutPaper { get; set; } = true;

    /// <summary>Kick the cash drawer open after printing a cash sale.</summary>
    public bool OpenCashDrawer { get; set; }

    /// <summary>Symbology for the barcode printed on the receipt: Code128, Code39, EAN-13, QR.</summary>
    public string BarcodeSymbology { get; set; } = "Code128";

    // ??? Navigation ???????????????????????????????????????????????????????????
    public ICollection<PosStore> Stores { get; set; } = new List<PosStore>();
}
