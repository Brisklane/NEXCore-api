using Nexcore.SharedKernel;
using Sales.Domain.Enums;

namespace Sales.Domain.Entities;

/// <summary>
/// A product line item within a POS transaction.
/// </summary>
public class PosTransactionLine : BaseEntity
{
    public Guid PosTransactionId { get; set; }
    public PosTransaction PosTransaction { get; set; } = null!;

    public int LineNumber { get; set; }

    // ??? Product ??????????????????????????????????????????????????????????????
    public Guid ProductId { get; set; }
    public string ProductCode { get; set; } = string.Empty;
    public string ProductName { get; set; } = string.Empty;
    public string? Barcode { get; set; }

    /// <summary>Optional: product variant (size, colour, etc.).</summary>
    public Guid? VariantId { get; set; }
    public string? VariantName { get; set; }

    // ??? Quantity & Pricing ???????????????????????????????????????????????????
    public decimal Quantity { get; set; }
    public string UnitOfMeasure { get; set; } = string.Empty;

    public decimal UnitPrice { get; set; }
    public decimal DiscountPercentage { get; set; }
    public decimal DiscountAmount { get; set; }
    public decimal NetUnitPrice { get; set; }
    public decimal LineAmount { get; set; }

    // ??? Tax ??????????????????????????????????????????????????????????????????
    public TaxCategory TaxCategory { get; set; } = TaxCategory.Standard;
    public decimal TaxRate { get; set; }
    public decimal TaxAmount { get; set; }

    public decimal TotalAmount { get; set; }

    public bool IsRefunded { get; set; }
    public decimal RefundedQuantity { get; set; }

    public string? Notes { get; set; }
}
