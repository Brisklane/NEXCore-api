using Nexcore.SharedKernel;
using Sales.Domain.Enums;

namespace Sales.Domain.Entities;

/// <summary>
/// An approval request raised for a specific SalesOrder under a matching ApprovalPolicy.
/// One ApprovalRequest is created per policy step when the order reaches PendingApproval.
///
/// The SalesOrder remains in PendingApproval until all steps are Approved.
/// Any single Rejected step cancels the entire approval chain.
/// </summary>
public class ApprovalRequest : BaseEntity
{
    public Guid SalesOrderId { get; set; }
    public SalesOrder SalesOrder { get; set; } = null!;

    public Guid ApprovalPolicyId { get; set; }
    public ApprovalPolicy ApprovalPolicy { get; set; } = null!;

    public Guid ApprovalPolicyStepId { get; set; }
    public ApprovalPolicyStep ApprovalPolicyStep { get; set; } = null!;

    public int StepOrder { get; set; }

    // ??? Routing ??????????????????????????????????????????????????????????????
    /// <summary>User this request was routed to at creation time.</summary>
    public Guid? AssignedUserId { get; set; }

    public string? AssignedRole { get; set; }

    // ??? Decision ?????????????????????????????????????????????????????????????
    public ApprovalDecision Decision { get; set; } = ApprovalDecision.Pending;

    public Guid? DecidedByUserId { get; set; }
    public DateTime? DecidedAt { get; set; }
    public string? Comments { get; set; }

    // ??? Escalation ???????????????????????????????????????????????????????????
    public bool IsEscalated { get; set; }
    public DateTime? EscalatedAt { get; set; }
    public Guid? EscalatedToUserId { get; set; }

    // ??? Timestamps ???????????????????????????????????????????????????????????
    public DateTime RequestedAt { get; set; } = DateTime.UtcNow;
    public DateTime? DueBy { get; set; }
}
