using Nexcore.SharedKernel;
using Sales.Domain.Enums;

namespace Sales.Domain.Entities;

/// <summary>
/// Gift card master record.
/// Can be sold at POS (creates a new record) and redeemed as a payment tender.
/// Inherited <c>CompanyId</c> / <c>BranchId</c> from <see cref="BaseEntity"/>
/// scope the card to the issuing company.
/// </summary>
public class PosGiftCard : BaseEntity
{
    // ??? Identity ?????????????????????????????????????????????????????????????
    /// <summary>Card number printed/encoded on the physical or digital card.</summary>
    public string CardNumber { get; set; } = string.Empty;

    /// <summary>Hashed PIN for verification at point of redemption.</summary>
    public string? PinHash { get; set; }

    // ??? Value ????????????????????????????????????????????????????????????????
    public decimal OriginalBalance { get; set; }
    public decimal CurrentBalance { get; set; }

    /// <summary>ISO 4217 currency code of the card balance.</summary>
    public string CurrencyCode { get; set; } = "USD";

    // ??? Status ???????????????????????????????????????????????????????????????
    public GiftCardStatus Status { get; set; } = GiftCardStatus.Active;

    // ??? Validity ?????????????????????????????????????????????????????????????
    public DateTime IssuedDate { get; set; } = DateTime.UtcNow;
    public DateTime? ExpiryDate { get; set; }

    // ??? Issued by ????????????????????????????????????????????????????????????
    /// <summary>The POS transaction in which this gift card was sold/issued.</summary>
    public Guid? IssuedInTransactionId { get; set; }
    public PosTransaction? IssuedInTransaction { get; set; }

    /// <summary>Cross-module reference to Crm.Contact. Null = anonymous. ID only.</summary>
    public Guid? ContactId { get; set; }

    public string? RecipientName { get; set; }
    public string? RecipientEmail { get; set; }
    public string? Message { get; set; }

    // ??? Navigation ???????????????????????????????????????????????????????????
    public ICollection<PosGiftCardTransaction> Transactions { get; set; } = new List<PosGiftCardTransaction>();
}
