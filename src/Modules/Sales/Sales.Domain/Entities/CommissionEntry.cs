using Nexcore.SharedKernel;
using Sales.Domain.Enums;

namespace Sales.Domain.Entities;

/// <summary>
/// Commission Entry — the actual commission earned by a sales rep on a specific order.
///
/// Generated automatically by the CommissionService when an order triggers a matching
/// CommissionRule. Can be approved and exported to payroll.
///
/// Aligned with:
///   Dynamics 365 — Commission Transaction
///   SAP  — Settlement document (rebate)
///   Odoo — sale.commission.line (OCA)
/// </summary>
public class CommissionEntry : BaseEntity
{
    public Guid SalesOrderId { get; set; }
    public SalesOrder SalesOrder { get; set; } = null!;

    /// <summary>The rule that generated this entry.</summary>
    public Guid CommissionRuleId { get; set; }
    public CommissionRule CommissionRule { get; set; } = null!;

    // ??? Who earns it ?????????????????????????????????????????????????????????
    /// <summary>Cross-module Guid to Auth.User / Hr.Employee — the sales rep.</summary>
    public Guid SalesRepId { get; set; }

    // ??? What triggered it ????????????????????????????????????????????????????
    /// <summary>
    /// Specific order line this commission relates to.
    /// Null when the commission is calculated at order header level.
    /// </summary>
    public Guid? SalesOrderLineId { get; set; }

    public Guid? SalesInvoiceId { get; set; }

    // ??? Amounts ??????????????????????????????????????????????????????????????
    /// <summary>The base amount the commission rate was applied to.</summary>
    public decimal BaseAmount { get; set; }

    /// <summary>Rate as used (snapshot from the rule at calculation time).</summary>
    public decimal CommissionRate { get; set; }

    /// <summary>Calculated commission amount = BaseAmount × CommissionRate (or fixed).</summary>
    public decimal CommissionAmount { get; set; }

    public string CurrencyCode { get; set; } = "USD";

    // ??? Status ???????????????????????????????????????????????????????????????
    public CommissionStatus Status { get; set; } = CommissionStatus.Pending;

    public DateTime EarnedDate { get; set; } = DateTime.UtcNow;
    public DateTime? ApprovedAt { get; set; }
    public DateTime? PaidAt { get; set; }

    /// <summary>Reference to payroll/accounting journal entry when paid.</summary>
    public Guid? PayrollEntryId { get; set; }

    public string? Notes { get; set; }
}
