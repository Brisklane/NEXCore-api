using Nexcore.SharedKernel;
using Sales.Domain.Enums;

namespace Sales.Domain.Entities;

/// <summary>
/// Rider / delivery agent profile.
/// A rider is a field agent who picks up and delivers online orders.
/// Can be an employee (HR FK) or a freelance contractor.
/// </summary>
public class Rider : BaseEntity
{
    // ??? Identity ?????????????????????????????????????????????????????????????
    public string RiderCode { get; set; } = string.Empty;
    public string FirstName { get; set; } = string.Empty;
    public string? LastName { get; set; }

    public string Phone { get; set; } = string.Empty;
    public string? Email { get; set; }
    public string? ProfileImageUrl { get; set; }

    public string? NationalId { get; set; }
    public DateTime? DateOfBirth { get; set; }

    // ??? Employment ???????????????????????????????????????????????????????????
    /// <summary>FK to HR Employee if the rider is a staff member.</summary>
    public Guid? HrEmployeeId { get; set; }

    /// <summary>Employee, Freelance, Outsourced.</summary>
    public string ContractType { get; set; } = "Employee";

    // ??? Assignment ???????????????????????????????????????????????????????????
    /// <summary>Home branch / hub this rider is based at. FK to Core.Branch by ID only.</summary>
    public Guid? HomeBranchId { get; set; }

    public Guid? ZoneId { get; set; }
    public DeliveryZone? Zone { get; set; }

    // ??? Vehicle ??????????????????????????????????????????????????????????????
    public VehicleType VehicleType { get; set; } = VehicleType.Motorcycle;
    public string? VehiclePlateNumber { get; set; }
    public string? VehicleModel { get; set; }
    public string? VehicleColor { get; set; }

    // ??? Status & Location ????????????????????????????????????????????????????
    public RiderStatus Status { get; set; } = RiderStatus.Offline;

    /// <summary>Last known GPS latitude.</summary>
    public double? CurrentLatitude { get; set; }

    /// <summary>Last known GPS longitude.</summary>
    public double? CurrentLongitude { get; set; }

    public DateTime? LastLocationUpdatedAt { get; set; }

    // ??? Performance ??????????????????????????????????????????????????????????
    public int TotalDeliveries { get; set; }
    public int SuccessfulDeliveries { get; set; }
    public int FailedDeliveries { get; set; }
    public decimal AverageRating { get; set; }

    // ??? Flags ????????????????????????????????????????????????????????????????
    public bool IsVerified { get; set; }

    public string? Notes { get; set; }

    // ??? Navigation ???????????????????????????????????????????????????????????
    public ICollection<RiderAssignment> Assignments { get; set; } = new List<RiderAssignment>();
    public ICollection<RiderShift> Shifts { get; set; } = new List<RiderShift>();
    public ICollection<RiderRating> Ratings { get; set; } = new List<RiderRating>();
}
