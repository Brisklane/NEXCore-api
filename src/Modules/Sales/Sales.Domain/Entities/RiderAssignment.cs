using Nexcore.SharedKernel;
using Sales.Domain.Enums;

namespace Sales.Domain.Entities;

/// <summary>
/// Dispatch assignment linking a Rider to an Online Order.
/// Created by the dispatch system (manual or auto-assigned).
/// Tracks the full pick-up ? delivery lifecycle with GPS timestamps.
/// </summary>
public class RiderAssignment : BaseEntity
{
    // ??? Identity ?????????????????????????????????????????????????????????????
    public string AssignmentNumber { get; set; } = string.Empty;

    // ??? Links ????????????????????????????????????????????????????????????????
    public Guid SalesOrderId { get; set; }
    public SalesOrder SalesOrder { get; set; } = null!;

    public Guid RiderId { get; set; }
    public Rider Rider { get; set; } = null!;

    // ??? Status ???????????????????????????????????????????????????????????????
    public RiderAssignmentStatus Status { get; set; } = RiderAssignmentStatus.Assigned;

    // ??? Timestamps ???????????????????????????????????????????????????????????
    public DateTime AssignedAt { get; set; } = DateTime.UtcNow;
    public DateTime? AcceptedAt { get; set; }
    public DateTime? RejectedAt { get; set; }
    public DateTime? ArrivedAtStoreAt { get; set; }
    public DateTime? PickedUpAt { get; set; }
    public DateTime? OutForDeliveryAt { get; set; }
    public DateTime? DeliveredAt { get; set; }
    public DateTime? FailedAt { get; set; }

    // ??? Pickup Location (Branch) ????????????????????????????????????????????
    /// <summary>Branch the rider picks up from. FK to Core.Branch by ID only.</summary>
    public Guid? PickupBranchId { get; set; }

    public double? PickupLatitude { get; set; }
    public double? PickupLongitude { get; set; }

    // ??? Delivery Location ????????????????????????????????????????????????????
    public double? DeliveryLatitude { get; set; }
    public double? DeliveryLongitude { get; set; }

    // ??? Distance & Duration ??????????????????????????????????????????????????
    public double? EstimatedDistanceKm { get; set; }
    public int? EstimatedDurationMinutes { get; set; }
    public double? ActualDistanceKm { get; set; }
    public int? ActualDurationMinutes { get; set; }

    // ??? Delivery Proof ???????????????????????????????????????????????????????
    public string? ProofImageUrl { get; set; }
    public string? RecipientName { get; set; }
    public string? RecipientSignatureUrl { get; set; }

    // ??? Failure ??????????????????????????????????????????????????????????????
    public string? FailureReason { get; set; }
    public bool IsReassigned { get; set; }
    public Guid? ReassignedToAssignmentId { get; set; }

    public string? Notes { get; set; }

    // ??? Navigation ???????????????????????????????????????????????????????????
    public ICollection<RiderLocationLog> LocationLogs { get; set; } = new List<RiderLocationLog>();
}
