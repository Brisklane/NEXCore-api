// ?? Create Invoice from Order (Odoo-style dialog) ???????????????????????????????????

/// <summary>
/// Request body for POST /api/sales/salesorder/{id}/create-invoice.
/// Mirrors Odoo's "Create invoices" dialog options.
/// </summary>
public class CreateInvoiceFromOrderDto
{
    /// <summary>
    /// Regular  — invoice all uninvoiced order-line quantities.
    /// DownPaymentPercentage / DownPaymentFixed — advance deposit invoice.
    /// </summary>
    public CreateInvoiceType InvoiceType { get; set; } = CreateInvoiceType.Regular;

    /// <summary>Required for DownPaymentPercentage (e.g. 30 for 30%).</summary>
    public decimal? DownPaymentPercentage { get; set; }

    /// <summary>Required for DownPaymentFixed (fixed monetary amount).</summary>
    public decimal? DownPaymentAmount { get; set; }

    /// <summary>Invoice due date. Defaults to 30 days from today.</summary>
    public DateTime? DueDate { get; set; }

    public string? CustomerReference { get; set; }
    public string? Notes { get; set; }
}
